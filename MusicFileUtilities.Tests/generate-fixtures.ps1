function New-TakStreamInfo {
    $fields = @(
        @([uint64]2, 6),          # mono/stereo codec
        @([uint64]0, 4),          # profile
        @([uint64]4, 4),          # 4096-sample frame type
        @([uint64]13230, 35),     # sample count
        @([uint64]0, 3),          # integer sample data
        @([uint64](44100 - 6000), 18),
        @([uint64](16 - 8), 5),
        @([uint64](2 - 1), 4),
        @([uint64]0, 1)           # no extended channel layout
    )
    [int]$totalBits = ($fields | ForEach-Object { $_[1] } |
        Measure-Object -Sum).Sum
    [byte[]]$result = [byte[]]::new([int][Math]::Ceiling($totalBits / 8.0))
    $bitOffset = 0
    foreach ($field in $fields) {
        [uint64]$value = $field[0]
        [int]$count = $field[1]
        for ($bit = 0; $bit -lt $count; $bit++) {
            if (($value -band ([uint64]1 -shl $bit)) -ne 0) {
                $byteIndex = [int][Math]::Floor(($bitOffset + $bit) / 8.0)
                $bitIndex = ($bitOffset + $bit) % 8
                $result[$byteIndex] = $result[$byteIndex] -bor (1 -shl $bitIndex)
            }
        }
        $bitOffset += $count
    }
    return ,$result
}

$takPath = Join-Path $OutDir 'sample.tak'
if (-not (Test-Path $takPath)) {
    $ms = [System.IO.MemoryStream]::new()
    $bw = [System.IO.BinaryWriter]::new($ms)
    $bw.Write([System.Text.Encoding]::ASCII.GetBytes('tBaK'))
    [byte[]]$info = New-TakStreamInfo
    [int]$blockSize = $info.Length + 3
    $bw.Write([byte]1)            # TAK_METADATA_STREAMINFO
    $bw.Write([byte]($blockSize -band 0xff))
    $bw.Write([byte](($blockSize -shr 8) -band 0xff))
    $bw.Write([byte](($blockSize -shr 16) -band 0xff))
    $bw.Write($info)
    $bw.Write([byte[]]::new(3))   # CRC24; parser validates bounds, not checksum
    $bw.Write([byte]0)            # TAK_METADATA_END
    $bw.Write([byte[]]::new(3))
    $bw.Write([byte[]](0..95 | ForEach-Object {
        [byte](($_ * 29 + 3) % 251)
    }))
    [byte[]]$tag = New-ApeV2Tag
    $bw.Write($tag)
    $bw.Flush()
    [System.IO.File]::WriteAllBytes($takPath, $ms.ToArray())
    $bw.Dispose()
    $ms.Dispose()
}

# --- official OptimFROG 5.100 reference fixtures -------------------------------------------
$optimFrogReferences = Join-Path $PSScriptRoot 'ReferenceFixtures\OptimFROG'
if ($RegenerateOptimFrog) {
    $tools = Resolve-OptimFrogTools
    $ffmpeg = Resolve-Ffmpeg
    New-Item -ItemType Directory -Force -Path $optimFrogReferences | Out-Null
    $integerWav = Join-Path $OutDir ".optimfrog-integer-$([guid]::NewGuid().ToString('N')).wav"
    $floatWav = Join-Path $OutDir ".optimfrog-float-$([guid]::NewGuid().ToString('N')).wav"
    try {
        & $ffmpeg -y -hide_banner -loglevel error @sine -c:a pcm_s16le $integerWav
        if ($LASTEXITCODE -ne 0) { throw "ffmpeg failed to create the OptimFROG integer source." }
        & $ffmpeg -y -hide_banner -loglevel error @sine -c:a pcm_f32le $floatWav
        if ($LASTEXITCODE -ne 0) { throw "ffmpeg failed to create the OptimFROG float source." }

        $ofrReference = Join-Path $optimFrogReferences 'sample.ofr'
        $ofsReference = Join-Path $optimFrogReferences 'sample.ofs'
        $offReference = Join-Path $optimFrogReferences 'sample.off'
        foreach ($path in @($ofrReference, $ofsReference, $offReference, "$offReference.ofr")) {
            Remove-Item -LiteralPath $path -Force -ErrorAction SilentlyContinue
        }

        & $tools.Ofr --encode $integerWav --output $ofrReference
        if ($LASTEXITCODE -ne 0) { throw "OptimFROG Lossless fixture encoding failed." }
        & $tools.Ofs --encode $integerWav --output $ofsReference
        if ($LASTEXITCODE -ne 0) { throw "OptimFROG DualStream fixture encoding failed." }
        & $tools.Off --encode $floatWav --output $offReference
        if ($LASTEXITCODE -ne 0) { throw "OptimFROG Float fixture encoding failed." }
        if (-not (Test-Path $offReference) -and (Test-Path "$offReference.ofr")) {
            Move-Item -LiteralPath "$offReference.ofr" -Destination $offReference
        }

        [byte[]]$optimFrogTag = New-ApeV2Tag
        foreach ($path in @($ofrReference, $ofsReference, $offReference)) {
            if (-not (Test-Path $path)) {
                throw "OptimFROG did not create expected fixture '$path'."
            }
            $tagStream = [System.IO.File]::Open(
                $path,
                [System.IO.FileMode]::Append,
                [System.IO.FileAccess]::Write,
                [System.IO.FileShare]::None)
            try {
                $tagStream.Write($optimFrogTag, 0, $optimFrogTag.Length)
            }
            finally {
                $tagStream.Dispose()
            }
        }
    }
    finally {
        Remove-Item -LiteralPath $integerWav -Force -ErrorAction SilentlyContinue
        Remove-Item -LiteralPath $floatWav -Force -ErrorAction SilentlyContinue
    }
}

foreach ($name in @('sample.ofr', 'sample.ofs', 'sample.off')) {
    $reference = Join-Path $optimFrogReferences $name
    if (-not (Test-Path $reference)) {
        throw "Required official OptimFROG fixture is missing: $reference. Regenerate it with -RegenerateOptimFrog."
    }
    Copy-Item -LiteralPath $reference -Destination (Join-Path $OutDir $name) -Force
}

# --- hand-crafted DSF fixture ---------------------------------------------------------------
$dsfPath = Join-Path $OutDir 'sample.dsf'
if (-not (Test-Path $dsfPath)) {
    $channels      = 2
    $blockPerChan  = 4096
    $samplingFreq  = 2822400      # DSD64
    $bitsPerSample = 1
    $dataPayload   = $channels * $blockPerChan         # one block per channel
    $sampleCount   = [uint64]($blockPerChan * 8)       # bits per channel

    $dsdChunkSize  = [uint64]28
    $fmtChunkSize  = [uint64]52
    $dataChunkSize = [uint64](12 + $dataPayload)       # 'data' + size(8) + payload
    $totalSize     = [uint64](28 + 52 + 12 + $dataPayload)

    $ms = New-Object System.IO.MemoryStream
    $bw = New-Object System.IO.BinaryWriter($ms)
    $ascii = [System.Text.Encoding]::ASCII

    # DSD chunk
    $bw.Write($ascii.GetBytes('DSD '))
    $bw.Write($dsdChunkSize)
    $bw.Write($totalSize)
    $bw.Write([uint64]0)                # metadata pointer = 0 (no tag yet)

    # fmt chunk
    $bw.Write($ascii.GetBytes('fmt '))
    $bw.Write($fmtChunkSize)
    $bw.Write([uint32]1)                # format version
    $bw.Write([uint32]0)                # format id (DSD raw)
    $bw.Write([uint32]2)                # channel type (stereo)
    $bw.Write([uint32]$channels)        # channel num
    $bw.Write([uint32]$samplingFreq)
    $bw.Write([uint32]$bitsPerSample)
    $bw.Write([uint64]$sampleCount)
    $bw.Write([uint32]$blockPerChan)
    $bw.Write([uint32]0)                # reserved

    # data chunk (0x69 is DSD silence)
    $bw.Write($ascii.GetBytes('data'))
    $bw.Write($dataChunkSize)
    $bw.Write((,[byte]0x69 * $dataPayload))

    $bw.Flush()
    [System.IO.File]::WriteAllBytes($dsfPath, $ms.ToArray())
    $bw.Dispose(); $ms.Dispose()
}

